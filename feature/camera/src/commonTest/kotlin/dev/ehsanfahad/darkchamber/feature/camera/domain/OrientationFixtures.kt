/**
 * Tiny 8×8 JPEGs for the orientation tests, **made by other tools**, never by the code under test.
 *
 * A test whose expected bytes came from the implementation can only pin the implementation's own
 * understanding — an earlier orientation table had two entries swapped, its test asserted the same
 * swap, and the feature was visibly wrong on screen while every test passed. So:
 *
 * - [JFIF_EXIF_MM] is macOS `sips` output (`sips -s format jpeg -z 8 8`): a JFIF APP0, then an EXIF
 *   APP1 in big-endian order whose first IFD holds Orientation = 1 **and** a pointer to an Exif
 *   sub-IFD, then a Photoshop APP13 — the shape a real camera file has, with offsets that must
 *   survive.
 * - [JFIF_EXIF_MM_3], [JFIF_EXIF_MM_6] and [JFIF_EXIF_MM_8] are exiftool's answer to
 *   `-n -Orientation=3|6|8` on that file. exiftool changes exactly one byte for each — the tag's
 *   value — which makes its output an exact external oracle for a rewrite in place.
 * - [EXIF_II_1] and [EXIF_II_6] are exiftool writing `-ExifByteOrder=II -Orientation#=1|6` onto
 *   [NO_METADATA]: the same rewrite in little-endian order.
 * - [EXIF_MM_6_INSERTED] is exiftool writing `-ExifByteOrder=MM -Orientation#=6` onto
 *   [NO_METADATA]: the block exiftool inserts into a file that has none — Orientation plus the
 *   YCbCrPositioning entry EXIF requires in a JPEG's first IFD — and so the exact answer for an
 *   insertion.
 * - [EXIF_MM_NO_ORIENTATION] is exiftool writing only `-Make=Fixture` — an EXIF block whose first
 *   IFD has entries but no orientation.
 * - [NO_METADATA] is the `sips` file with every segment stripped by `exiftool -all=`: SOI straight
 *   into SOF0. [JFIF_ONLY] is the same with only the JFIF APP0 kept.
 *
 * Regenerate rather than hand-edit.
 */
