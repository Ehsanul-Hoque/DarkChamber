#!/bin/bash
# Writes the clips in ../assets/video/ into an iOS test source file, as base64: a Kotlin/Native test
# has no asset folder to read, and these are the same ffmpeg-made files the Android tests read, byte
# for byte. Run from this directory after make-video-fixtures.sh:
#   ./embed-video-fixtures-for-ios.sh ../assets/video \
#     ../../../../app/src/iosTest/kotlin/dev/ehsanfahad/darkchamber/app/thumbnail/VideoFixtures.kt
set -euo pipefail
IN="$1"
OUT="$2"
# file : Kotlin property : constant
CLIPS="colour:colour:COLOUR colour-faststart:colourFaststart:COLOUR_FASTSTART sparse-keys:sparseKeys:SPARSE_KEYS rotated:rotated:ROTATED short:short:SHORT audio-only:audioOnly:AUDIO_ONLY"
{
  echo "package dev.ehsanfahad.darkchamber.app.thumbnail"
  echo ""
  echo "// Generated by androidApp/src/androidTest/fixtures/embed-video-fixtures-for-ios.sh from the"
  echo "// ffmpeg-made clips in androidApp/src/androidTest/assets/video/. Do not edit by hand."
  echo ""
  echo "import kotlin.io.encoding.Base64"
  echo ""
  echo "internal object VideoFixtures {"
  for clip in $CLIPS; do
    IFS=: read -r file property constant <<< "$clip"
    echo "    val $property: ByteArray get() = Base64.decode(${constant}_B64)"
  done
  echo "}"
  for clip in $CLIPS; do
    IFS=: read -r file property constant <<< "$clip"
    echo ""
    echo "private const val ${constant}_B64 ="
    base64 -i "$IN/$file.mp4" | tr -d '\n' | fold -w 96 | sed 's/^/    "/; s/$/" +/' | sed '$ s/ +$//'
  done
} > "$OUT"
