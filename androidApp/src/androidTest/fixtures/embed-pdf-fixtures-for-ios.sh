#!/bin/bash
# Writes the PDFs in ../assets/pdf/ into an iOS test source file, as base64: a Kotlin/Native test has
# no asset folder to read, and these are the same CoreGraphics-made files the Android tests read, byte
# for byte. Run from this directory after make-pdf-fixtures.swift:
#   ./embed-pdf-fixtures-for-ios.sh ../assets/pdf \
#     ../../../../app/src/iosTest/kotlin/dev/ehsanfahad/darkchamber/app/pdf/PdfFixtures.kt
set -euo pipefail
IN="$1"
OUT="$2"
# file : Kotlin property : constant
FILES="plain:plain:PLAIN locked:locked:LOCKED truncated:truncated:TRUNCATED halves:halves:HALVES"
mkdir -p "$(dirname "$OUT")"
{
  echo "package dev.ehsanfahad.darkchamber.app.pdf"
  echo ""
  echo "// Generated by androidApp/src/androidTest/fixtures/embed-pdf-fixtures-for-ios.sh from the"
  echo "// CoreGraphics-made PDFs in androidApp/src/androidTest/assets/pdf/. Do not edit by hand."
  echo ""
  echo "import kotlin.io.encoding.Base64"
  echo ""
  echo "internal object PdfFixtures {"
  for entry in $FILES; do
    IFS=: read -r file property constant <<< "$entry"
    echo "    val $property: ByteArray get() = Base64.decode(${constant}_B64)"
  done
  echo "}"
  echo ""
  for entry in $FILES; do
    IFS=: read -r file property constant <<< "$entry"
    echo "private const val ${constant}_B64 ="
    echo "    \"$(base64 -i "$IN/$file.pdf" | tr -d '\n')\""
    echo ""
  done
} > "$OUT"
